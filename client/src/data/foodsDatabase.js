/**
 * Fast client-side fuzzy food search
 * Supports search by name, partial word matches, synonyms, and Indian terms (e.g. 'chawal', 'phulka', 'dahi')
 */
export function searchFoodsLocal(query, limit = 20) {
  if (!query || typeof query !== 'string' || !query.trim()) {
    // Return a curated selection of popular staples when search query is empty
    return INDIAN_AND_GLOBAL_FOODS.slice(0, 8);
  }

  const cleanQuery = query.trim().toLowerCase();
  const searchTerms = cleanQuery.split(/\s+/).filter(Boolean);

  const scoredResults = [];

  for (const food of INDIAN_AND_GLOBAL_FOODS) {
    const foodName = food.name.toLowerCase();
    const keywords = (food.keywords || []).map((k) => k.toLowerCase());
    const category = (food.category || '').toLowerCase();

    let score = 0;

    // Exact name match
    if (foodName === cleanQuery) {
      score += 100;
    } else if (foodName.startsWith(cleanQuery)) {
      score += 60;
    } else if (foodName.includes(cleanQuery)) {
      score += 40;
    }

    // Keyword matches
    for (const kw of keywords) {
      if (kw === cleanQuery) {
        score += 80;
      } else if (kw.startsWith(cleanQuery)) {
        score += 45;
      } else if (kw.includes(cleanQuery)) {
        score += 25;
      }
    }

    // Multi-term matching (e.g. 'aloo paratha')
    let allTermsMatch = true;
    for (const term of searchTerms) {
      const termMatchesName = foodName.includes(term);
      const termMatchesKeywords = keywords.some((k) => k.includes(term));
      const termMatchesCat = category.includes(term);

      if (termMatchesName || termMatchesKeywords || termMatchesCat) {
        score += 15;
      } else {
        allTermsMatch = false;
      }
    }

    if (allTermsMatch && searchTerms.length > 1) {
      score += 30;
    }

    if (score > 0) {
      scoredResults.push({ food, score });
    }
  }

  // Sort descending by relevance score
  scoredResults.sort((a, b) => b.score - a.score);

  return scoredResults.slice(0, limit).map((r) => r.food);
}

